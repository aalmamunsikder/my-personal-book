/**
 * Resolves full effective appearance by applying inheritance cascade:
 * Factory Defaults -> Owner Global Config -> Collection Overrides -> Entry Template Override
 */
export function resolveEffectiveAppearance(
  globalConfig: AppearanceConfig | null | undefined,
  collectionOverride?: Partial<AppearanceConfig> | null,
  entryTemplateId?: PageTemplateId | null
): AppearanceConfig {
  const base: AppearanceConfig = {
    ...DEFAULT_APPEARANCE_CONFIG,
    ...(globalConfig || {}),
    colors: {
      ...DEFAULT_APPEARANCE_CONFIG.colors,
      ...(globalConfig?.colors || {}),
    },
    typography: {
      ...DEFAULT_APPEARANCE_CONFIG.typography,
      ...(globalConfig?.typography || {}),
    },
    decorations: {
      ...DEFAULT_APPEARANCE_CONFIG.decorations,
      ...(globalConfig?.decorations || {}),
    },
  };

  // Safe fallback if IDs are unknown or corrupted
  if (!FACTORY_THEMES[base.appThemeId]) base.appThemeId = 'heritage-parchment';
  if (!PAPER_SURFACES[base.paperId]) base.paperId = 'cream-stationery';
  if (!PAGE_TEMPLATES[base.pageTemplateId]) base.pageTemplateId = 'classic-journal';
  if (!TYPOGRAPHY_PRESETS[base.typographyPresetId]) base.typographyPresetId = 'classic-literary';

  // Apply collection overrides if present
  if (collectionOverride) {
    if (collectionOverride.appThemeId && FACTORY_THEMES[collectionOverride.appThemeId]) {
      base.appThemeId = collectionOverride.appThemeId;
    }
    if (collectionOverride.paperId && PAPER_SURFACES[collectionOverride.paperId]) {
      base.paperId = collectionOverride.paperId;
    }
    if (collectionOverride.pageTemplateId && PAGE_TEMPLATES[collectionOverride.pageTemplateId]) {
      base.pageTemplateId = collectionOverride.pageTemplateId;
    }
    if (collectionOverride.typographyPresetId && TYPOGRAPHY_PRESETS[collectionOverride.typographyPresetId]) {
      base.typographyPresetId = collectionOverride.typographyPresetId;
    }
    if (collectionOverride.coverId && COVER_STYLES[collectionOverride.coverId]) {
      base.coverId = collectionOverride.coverId;
    }
    if (collectionOverride.colors) {
      base.colors = { ...base.colors, ...collectionOverride.colors };
    }
  }

  // Apply entry-level template override if set
  if (entryTemplateId && PAGE_TEMPLATES[entryTemplateId]) {
    base.pageTemplateId = entryTemplateId;
  }

  return base;
}
